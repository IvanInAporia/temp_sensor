/**
  * @brief  Bring up the Wi-Fi rail, then hand PA2/PA3 over to LPUART1.
  * @note   Order matters.  PA2 (LPUART1_TX) idles high, push-pull at VDD.
  *         With U5 off, that current leaves through the T3-3S input ESD
  *         diode and part-powers VBAT; U5's QOD pin is unconnected, so
  *         nothing discharges the rail afterwards.  Power first, drive
  *         second.
  */
void Wifi_RailOn(void)
{
  HAL_GPIO_WritePin(OUT_WIFI_ON_GPIO_Port, OUT_WIFI_ON_Pin, GPIO_PIN_SET);
  HAL_Delay(WIFI_RAIL_TON_MS);
  MX_LPUART1_UART_Init();
}

/**
  * @brief  Park PA2/PA3, then cut the Wi-Fi rail.
  * @note   HAL_UART_DeInit() runs HAL_UART_MspDeInit(), which calls
  *         HAL_GPIO_DeInit() on PA2/PA3.  That leaves both pins in analog
  *         mode (MODER = 0b11), so there is no drive, no Schmitt trigger
  *         and no leakage path into the unpowered module.
  */
void Wifi_RailOff(void)
{
  HAL_UART_DeInit(&hlpuart1);
  HAL_GPIO_WritePin(OUT_WIFI_ON_GPIO_Port, OUT_WIFI_ON_Pin, GPIO_PIN_RESET);
}

